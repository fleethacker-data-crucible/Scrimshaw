// Generates src/ui/icons.tsx from Lucide's SVG sources, so the app bundles only the
// icons it uses and never loads anything from a CDN.
//   node tools/gen-icons.mjs <path-to-lucide>/icons
// The output is committed; re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
const NAMES = `undo-2 redo-2 play pause eye eye-off download upload file-plus folder-open save type square
circle image mouse-pointer-click square-dashed text-cursor-input list-checks video plus trash copy
chevron-up chevron-down chevron-right chevron-left layers zap variable settings sun moon x
align-start-vertical align-center-vertical align-end-vertical align-start-horizontal
align-center-horizontal align-end-horizontal bring-to-front send-to-back arrow-up arrow-down lock
lock-open workflow menu circle-check circle-x rotate-ccw monitor-play package grid-3x3 magnet zoom-in
zoom-out scan message-square-text list-ordered pencil ellipsis square-check file-braces globe triangle
arrow-right clipboard-paste scissors square-mouse-pointer circle-dot gauge book-open skip-forward
skip-back clock maximize keyboard info triangle-alert trophy flag volume-2 log-out`.split(/\s+/).filter(Boolean);

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/gen-icons.mjs <lucide>/icons'); process.exit(1); }
const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const out = [];
for (const name of NAMES) {
  const svg = readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()
    .replace(/\s*\n\s*/g, '')
    .replace(/stroke-width/g, 'strokeWidth');
  out.push(`export const ${pascal(name)} = (p: IconProps) => <Svg {...p}>${inner}</Svg>;`);
}
const header = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
import type { SVGProps } from 'react';
export type IconProps = SVGProps<SVGSVGElement> & { size?: number };
function Svg({ size = 16, children, ...rest }: IconProps) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none"
      stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round"
      aria-hidden="true" focusable="false" {...rest}>{children}</svg>
  );
}
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui', 'icons.tsx');
writeFileSync(target, header + out.join('\n') + '\n');
console.log(`wrote ${NAMES.length} icons to ${target}`);
